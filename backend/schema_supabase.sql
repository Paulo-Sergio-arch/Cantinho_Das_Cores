-- Cantinho das Cores — Schema oficial para PostgreSQL / Supabase
-- Equivalente 1:1 ao schema.sql original da equipe (SQLite), adaptado para dialeto PostgreSQL 15+ / Supabase,
-- incluindo coluna 'nome' em responsaveis, preferência 'voz_ativa' em criancas e tabelas de segurança/recuperação.
-- Como aplicar no Supabase:
-- 1. Abra o painel do projeto no Supabase -> SQL Editor -> New Query
-- 2. Cole todo este arquivo e clique em "Run" (ou a própria API executa init_db() automaticamente ao iniciar).
-- 3. Configure DATABASE_URL no servidor da API FastAPI (Render) usando a Connection String do PostgreSQL.

CREATE TABLE IF NOT EXISTS responsaveis (
    id_responsavel INTEGER     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email          TEXT        NOT NULL
                               CHECK (length(email) >= 6 AND position('@' IN email) > 1),
    senha          TEXT        NOT NULL CHECK (length(senha) >= 40),
    aceito_termo   INTEGER     NOT NULL CHECK (aceito_termo = 1),
    aceito_em      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    nome           TEXT
);

-- Migração idempotente caso a tabela responsaveis já tenha sido criada sem a coluna nome
ALTER TABLE responsaveis ADD COLUMN IF NOT EXISTS nome TEXT;

-- Unicidade de e-mail sem diferenciar maiúsculas/minúsculas (equivalente ao UNIQUE COLLATE NOCASE do SQLite)
CREATE UNIQUE INDEX IF NOT EXISTS uq_responsaveis_email_lower ON responsaveis (lower(email));

CREATE TABLE IF NOT EXISTS criancas (
    id_crianca     INTEGER     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_responsavel INTEGER     NOT NULL,
    apelido        TEXT        NOT NULL CHECK (length(trim(apelido)) > 0),
    idade          INTEGER     NOT NULL CHECK (idade BETWEEN 3 AND 18),
    voz_ativa      INTEGER     NOT NULL DEFAULT 1 CHECK (voz_ativa IN (0, 1)),
    criado_em      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (id_responsavel) REFERENCES responsaveis(id_responsavel) ON DELETE CASCADE
);

ALTER TABLE criancas ADD COLUMN IF NOT EXISTS voz_ativa INTEGER NOT NULL DEFAULT 1;

CREATE TABLE IF NOT EXISTS jogos (
    id_jogo    TEXT NOT NULL PRIMARY KEY,
    nome       TEXT NOT NULL,
    habilidade TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS partidas (
    id_partida  INTEGER     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_crianca  INTEGER     NOT NULL,
    id_jogo     TEXT        NOT NULL,
    acertos     INTEGER     NOT NULL DEFAULT 0 CHECK (acertos BETWEEN 0 AND 5),
    erros       INTEGER     NOT NULL DEFAULT 0 CHECK (erros >= 0),
    duracao_seg INTEGER     CHECK (duracao_seg >= 0),
    pontuacao   INTEGER     NOT NULL DEFAULT 0 CHECK (pontuacao BETWEEN 0 AND 100),
    concluida   INTEGER     NOT NULL DEFAULT 0 CHECK (concluida IN (0, 1)),
    jogado_em   TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (concluida = 0 OR acertos = 5),          -- só é "concluída" com 5 acertos
    FOREIGN KEY (id_crianca) REFERENCES criancas(id_crianca) ON DELETE CASCADE,
    FOREIGN KEY (id_jogo)    REFERENCES jogos(id_jogo)       ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS relatorios (
    id_relatorio   INTEGER     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_crianca     INTEGER     NOT NULL,
    periodo_inicio DATE        NOT NULL,
    periodo_fim    DATE        NOT NULL,
    texto          TEXT        NOT NULL CHECK (length(trim(texto)) > 0),
    gerado_em      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    enviado_em     TIMESTAMPTZ,
    CHECK (periodo_fim >= periodo_inicio),
    FOREIGN KEY (id_crianca) REFERENCES criancas(id_crianca) ON DELETE CASCADE
);
-- Destaques do relatório (JSON com os pedaços do texto e a origem de cada um); antigos ficam NULL
ALTER TABLE relatorios ADD COLUMN IF NOT EXISTS destaques TEXT;

-- Tabelas auxiliares de segurança da API FastAPI (revogação de JWT, recuperação de senha e rate limiting)
CREATE TABLE IF NOT EXISTS tokens_revogados (
    jti         TEXT        PRIMARY KEY,
    revogado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expira_em   TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS tokens_recuperacao_senha (
    token_hash     TEXT             PRIMARY KEY,
    id_responsavel INTEGER          NOT NULL,
    expira_em      DOUBLE PRECISION NOT NULL,
    usado          INTEGER          NOT NULL DEFAULT 0,
    FOREIGN KEY (id_responsavel) REFERENCES responsaveis(id_responsavel) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS tentativas_login (
    chave     TEXT             NOT NULL,
    criado_em DOUBLE PRECISION NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_criancas_responsavel   ON criancas(id_responsavel);
CREATE INDEX IF NOT EXISTS idx_partidas_crianca_jogo  ON partidas(id_crianca, id_jogo);
CREATE INDEX IF NOT EXISTS idx_relatorios_crianca     ON relatorios(id_crianca);
CREATE INDEX IF NOT EXISTS idx_tentativas_login_chave ON tentativas_login(chave, criado_em);

CREATE OR REPLACE VIEW v_desempenho AS
SELECT c.id_crianca,
       c.apelido,
       c.idade,
       j.id_jogo,
       j.nome AS jogo,
       j.habilidade,
       COUNT(p.id_partida)       AS partidas_concluidas,
       ROUND(AVG(p.pontuacao))   AS pontuacao_media,
       SUM(p.erros)              AS total_erros,
       ROUND(AVG(p.duracao_seg)) AS tempo_medio_seg,
       MAX(p.jogado_em)          AS ultima_vez
FROM criancas c
CROSS JOIN jogos j
LEFT JOIN partidas p
       ON p.id_crianca = c.id_crianca AND p.id_jogo = j.id_jogo AND p.concluida = 1
GROUP BY c.id_crianca, c.apelido, c.idade, j.id_jogo, j.nome, j.habilidade;

