-- Proteção recomendada para Supabase: habilita Row Level Security (RLS) em todas as tabelas
-- para bloquear acesso direto via chave pública anon/PostgREST, mantendo o acesso completo
-- da API FastAPI pela conexão direta PostgreSQL (DATABASE_URL).
ALTER TABLE responsaveis             ENABLE ROW LEVEL SECURITY;
ALTER TABLE criancas                 ENABLE ROW LEVEL SECURITY;
ALTER TABLE jogos                    ENABLE ROW LEVEL SECURITY;
ALTER TABLE partidas                 ENABLE ROW LEVEL SECURITY;
ALTER TABLE relatorios               ENABLE ROW LEVEL SECURITY;
ALTER TABLE tokens_revogados         ENABLE ROW LEVEL SECURITY;
ALTER TABLE tokens_recuperacao_senha ENABLE ROW LEVEL SECURITY;
ALTER TABLE tentativas_login         ENABLE ROW LEVEL SECURITY;
